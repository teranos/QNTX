// Command openapi writes the machine-readable half of what the node serves.

// One source: server/reach's table, which is what the node serves. A path
// nothing grants is not served at all, so the table is the path list.

// It is read through reach.Reached, the same parser the mux reads it with, so
// the document cannot say something the mux does not do.

// Nothing is read from source. What is done on a path is a sigil's to say, and
// the node lays each sigil's operations in as it serves the document (ADR-039).
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/teranos/QNTX/server/reach"
	"github.com/teranos/errors"
)

// Where the document is written. It lives beside the package that serves it,
// because Go embeds a file only from its own directory downward.
const writtenTo = "server/openapi/openapi.json"

func main() {
	root := flag.String("root", ".", "the QNTX checkout to write into")
	out := flag.String("out", writtenTo, "where to write the document")
	flag.Parse()

	document, err := build()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	body, err := json.MarshalIndent(document, "", "  ")
	if err != nil {
		fmt.Fprintln(os.Stderr, errors.Wrap(err, "the document did not marshal"))
		os.Exit(1)
	}
	body = append(body, '\n')

	path := filepath.Join(*root, *out)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, errors.Wrapf(err, "failed to make the directory for %s", path))
		os.Exit(1)
	}
	if err := os.WriteFile(path, body, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, errors.Wrapf(err, "failed to write %s", path))
		os.Exit(1)
	}
	fmt.Printf("%s: %d paths\n", path, len(document.Paths))
}

// Document is an OpenAPI 3.1 document. 3.1 rather than 3.0 because a path
// there may hold no operation, and this file knows none.
type Document struct {
	OpenAPI string               `json:"openapi"`
	Info    Info                 `json:"info"`
	Paths   map[string]*PathItem `json:"paths"`
}

type Info struct {
	Title string `json:"title"`
	// Version is absent from the written file and filled in at serve time.
	// OpenAPI requires it, so a reader of the file alone sees an empty string
	// rather than a version that was true when somebody last ran the tool.
	Version     string `json:"version"`
	Description string `json:"description"`
}

// PathItem is one path the table names. The x-qntx- fields are what QNTX
// knows and OpenAPI has no word for: who reaches the path.
type PathItem struct {
	Reached []string `json:"x-qntx-reach"`
	// Prefix is a path Go's mux matches by prefix rather than exactly —
	// /api/prose/ answers /api/prose/anything. It is not OpenAPI templating,
	// and saying so is the difference between a path and a family of them.
	Prefix bool `json:"x-qntx-prefix,omitempty"`
}

// build reads the table.
func build() (*Document, error) {
	reached, err := reach.Reached()
	if err != nil {
		return nil, errors.Wrap(err, "the reach table did not read")
	}

	paths := map[string]*PathItem{}
	for _, path := range sorted(reached) {
		paths[path] = &PathItem{
			Reached: reached[path],
			Prefix:  strings.HasSuffix(path, "/") && path != "/",
		}
	}

	// No version. The tag is the only source of one and it does not exist yet:
	// this file is committed, and the tag is cut on the commit that carries it.
	// server/openapi_handler.go fills it in when a node serves the document.
	return &Document{
		OpenAPI: "3.1.0",
		Info: Info{
			Title: "QNTX",
			Description: "Generated by cmd/openapi from server/reach's table. Never edited by hand. " +
				"The version is the serving node's, and what a sigil does on a path is laid in " +
				"by the node as it answers.",
		},
		Paths: paths,
	}, nil
}

func sorted[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for key := range m {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}
